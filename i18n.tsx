const extraTranslationFallbacks: Record<Exclude<LanguageCode, 'fi' | 'sv' | 'en'>, typeof extraTranslations.en> = {
  uk: extraTranslations.en,
  et: extraTranslations.en,
  ru: extraTranslations.en,
  se: extraTranslations.en,
};

type TranslationKey = keyof typeof translations.fi;
type ExtraTranslationKey = keyof typeof extraTranslations.fi;

interface I18nContextValue {
  language: LanguageCode;
  setLanguage: (language: LanguageCode) => void;
  locale: string;
  speechLocale: string;
  t: (key: TranslationKey | ExtraTranslationKey) => string;
  categoryName: (name: string) => string;
}

const I18nContext = createContext<I18nContextValue | null>(null);

const isLanguageCode = (value: string | null): value is LanguageCode => (
  Boolean(value && LANGUAGES.some((language) => language.code === value))
);

const detectBrowserLanguage = (): LanguageCode => {
  if (typeof navigator === 'undefined') return 'fi';

  const languageMap: Record<string, LanguageCode> = {
    fi: 'fi',
    sv: 'sv',
    en: 'en',
    uk: 'uk',
    et: 'et',
    ru: 'ru',
    se: 'se',
    sme: 'se',
    smn: 'se',
    sms: 'se',
  };

  for (const language of navigator.languages ?? [navigator.language]) {
    const normalized = language.toLocaleLowerCase().split('-')[0];
    const mapped = languageMap[normalized];
    if (mapped) return mapped;
  }

  return 'fi';
};

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [language, setLanguageState] = useState<LanguageCode>(() => {
    try {
      const saved = localStorage.getItem(LANGUAGE_STORAGE_KEY);
      return isLanguageCode(saved) ? saved : detectBrowserLanguage();
    } catch {
      return detectBrowserLanguage();
    }
  });

  useEffect(() => {
    try {
      localStorage.setItem(LANGUAGE_STORAGE_KEY, language);
    } catch {
      // Ignore storage errors.
    }
    document.documentElement.lang = language;
  }, [language]);

  const value = useMemo<I18nContextValue>(() => {
    const languageInfo = LANGUAGES.find((item) => item.code === language) ?? LANGUAGES[0];
    return {
      language,
      setLanguage: setLanguageState,
      locale: languageInfo.locale,
      speechLocale: languageInfo.speechLocale,
      t: (key) => (
        (translations[language] as Record<string, string>)[key]
        ?? (extraTranslations[language as keyof typeof extraTranslations] as Record<string, string> | undefined)?.[key]
        ?? (extraTranslationFallbacks[language as keyof typeof extraTranslationFallbacks] as Record<string, string> | undefined)?.[key]
        ?? (translations.fi as Record<string, string>)[key]
        ?? (extraTranslations.fi as Record<string, string>)[key]
        ?? key
      ),
      categoryName: (name) => translateCategoryName(name, language),
    };
  }, [language]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
};

export const useI18n = () => {
  const context = useContext(I18nContext);
  if (!context) {
    throw new Error('useI18n must be used inside LanguageProvider');
  }
  return context;
};
